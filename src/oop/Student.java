package oop;

public class Student {
    private String name;
    private int age;
    private String school;

    public void setName(String _name){
        this.name = _name;
    }

    public String getName(){
        return this.name;
    }

    public void setAge(int _age){
        this.age = _age;
    }

    public int getAge(){
        return this.age;
    }

    public void setSchool(String _school){
        this.school = _school;
    }

    public String getSchool(){
        return this.school;
    }

}
